  String t(String key, [Map<String, Object> params = const {}]) {
    final language = _values.containsKey(locale.languageCode)
        ? locale.languageCode
        : 'en';
    var value = _values[language]?[key] ?? _values['en']![key] ?? key;
    for (final entry in params.entries) {
